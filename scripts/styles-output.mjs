import { FILE_PREFIX } from "@terrazzo/plugin-css";

// Suppress descriptions before the CSS plugin prints declarations. Values may
// contain comment-like text, so they never pass through a comment-removal regex.
export function valuesOnly(plugin) {
  return {
    ...plugin,
    build(context) {
      return plugin.build({
        ...context,
        getTransforms: (...args) =>
          context.getTransforms(...args).map((record) => ({
            ...record,
            token: { ...record.token, $description: undefined },
            meta: {
              ...record.meta,
              "plugin-css": { ...record.meta?.["plugin-css"], description: "" },
            },
          })),
        outputFile(name, contents) {
          const banner = name.endsWith(".css")
            ? FILE_PREFIX
            : "////\n/// Autogenerated by ⛋ Terrazzo. DO NOT EDIT!\n////\n";
          if (contents.startsWith(banner))
            contents = contents.slice(banner.length);
          context.outputFile(
            name,
            `${name.endsWith(".css") ? indent(contents) : contents.trim()}\n`,
          );
        },
      });
    },
  };
}

// The plugin prints declaration blocks; the enclosing media and preference
// blocks come from this build. Give both the same indentation.
function indent(text) {
  let depth = 0;
  const lines = [];
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith("}")) depth = Math.max(0, depth - 1);
    lines.push("  ".repeat(depth) + line);
    if (line.endsWith("{")) depth++;
    if (line.startsWith("}") && depth === 0) lines.push("");
  }
  return lines.join("\n").trim();
}
