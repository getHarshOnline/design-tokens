// Portable standalone-theme snapshots of the same outputs bound by the workspace.
// Normal site rendering reads design-tokens/dist directly through resource_inputs.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
async function files(directory) {
  const entries = await readdir(directory, {withFileTypes: true});
  const found = await Promise.all(entries.map(entry => entry.isDirectory() ? files(resolve(directory, entry.name)) : [resolve(directory, entry.name)]));
  return found.flat().sort();
}
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputs = [
  '.nvmrc', 'package.json', 'package-lock.json', 'resolver.json',
  'terrazzo.config.mjs',
  ...(await files(resolve(root, 'scripts'))).filter(path => path.endsWith('.mjs')).map(path => path.slice(root.length + 1)),
  ...(await files(resolve(root, 'tokens'))).filter(path => path.endsWith('.json')).map(path => path.slice(root.length + 1)),
].sort();
const inventory = (await Promise.all(inputs.map(async path => `${digest(await readFile(resolve(root, path)))}  ${path}\n`))).join('');
const check = process.argv.includes('--check');
const contexts = JSON.parse(await readFile(resolve(root, 'resolver.json'), 'utf8')).modifiers.world.contexts;
const worlds = Object.keys(contexts).map(name => name === 'neutral' ? 'base' : name);
for (const world of worlds) {
  const theme = resolve(root, '..', `gazette-theme-${world}`);
  // Planned themes without a token resource are not capture consumers.
  let manifest;
  try { manifest = await readFile(resolve(theme, 'presentation.toml'), 'utf8'); }
  catch (error) { if (error.code === 'ENOENT') continue; throw error; }
  if (!manifest.includes(`tokens/${world === 'base' ? 'base' : 'world'}.css`)) continue;
  for (const style of await files(resolve(theme, 'styles'))) {
    if (/layout-test-width-/.test(await readFile(style, 'utf8'))) throw new Error(`Production style uses a verification width: ${style}`);
  }
  const hashes = [];
  for (const [source, destination] of [[`css/${world}.css`, world === 'base' ? 'base.css' : 'world.css'], ['scss/_layout.scss', 'scss/_layout.scss']]) {
    const bytes = await readFile(resolve(root, 'dist', source));
    hashes.push(`- ${destination}: \`${digest(bytes)}\``);
    const target = resolve(theme, 'tokens', destination);
    if (check) {
      if (!bytes.equals(await readFile(target))) throw new Error(`Stale token capture: ${world}/${destination}`);
    } else await writeFile(target, bytes);
  }
  const provenance = `# Generated token capture\n\nGenerated by design-tokens/scripts/capture-themes.mjs from the canonical producer.\nNormal workspace rendering mounts the producer outputs; these identical copies support standalone theme fixtures.\n\n${hashes.join('\n')}\n\nGenerator input inventory SHA-256: \`${digest(inventory)}\`.\n\n\`\`\`text\n${inventory}\`\`\`\n\nRebuild with \`npm run build && npm run capture\`; verify with \`npm run check:captures\`.\nThis record establishes input bytes, not design approval or release qualification.\n`;
  const source = resolve(theme, 'tokens/SOURCE.md');
  if (check) {
    if (await readFile(source, 'utf8') !== provenance) throw new Error(`Stale token provenance: ${world}`);
  } else await writeFile(source, provenance);
}
console.log(check ? 'All theme token captures match the producer.' : 'Updated portable theme token captures.');
